// Función helper para saber qué características aplican a cada tipo de propiedad
export function getPropertyTypeFeatures(propertyType: Property['propertyType']) {
  const features = {
    hasBedrooms: true,
    hasBathrooms: true,
    hasFloor: true,
    hasYearBuilt: true,
    hasCondition: true,
    hasOrientation: true,
    hasEnergyRating: true,
    hasElevator: true,
    hasAirConditioning: true,
    hasHeating: true,
    hasParking: true,
    hasStorage: true,
    hasTerrace: true,
    hasBalcony: true,
    hasGarden: true,
    hasPool: true,
    hasWardrobes: true,
    hasFurnished: true,
    hasAccessible: true,
  };

  // Terrenos: solo área, orientación y energía
  if (propertyType === 'land') {
    return {
      ...features,
      hasBedrooms: false,
      hasBathrooms: false,
      hasFloor: false,
      hasYearBuilt: false,
      hasCondition: false,
      hasElevator: false,
      hasAirConditioning: false,
      hasHeating: false,
      hasStorage: false,
      hasTerrace: false,
      hasBalcony: false,
      hasWardrobes: false,
      hasFurnished: false,
    };
  }

  // Naves: sin habitaciones, sin balcón
  if (propertyType === 'warehouse') {
    return {
      ...features,
      hasBedrooms: false,
      hasBathrooms: false,
      hasBalcony: false,
      hasWardrobes: false,
      hasFurnished: false,
      hasGarden: false,
      hasPool: false,
    };
  }

  // Garajes: solo área y acceso
  if (propertyType === 'garage') {
    return {
      ...features,
      hasBedrooms: false,
      hasBathrooms: false,
      hasYearBuilt: false,
      hasCondition: false,
      hasOrientation: false,
      hasElevator: false,
      hasAirConditioning: false,
      hasHeating: false,
      hasStorage: false,
      hasTerrace: false,
      hasBalcony: false,
      hasGarden: false,
      hasPool: false,
      hasWardrobes: false,
      hasFurnished: false,
    };
  }

  // Trasteros: solo área básica
  if (propertyType === 'storage') {
    return {
      ...features,
      hasBedrooms: false,
      hasBathrooms: false,
      hasYearBuilt: false,
      hasCondition: false,
      hasOrientation: false,
      hasElevator: false,
      hasAirConditioning: false,
      hasHeating: false,
      hasParking: false,
      hasStorage: false,
      hasTerrace: false,
      hasBalcony: false,
      hasGarden: false,
      hasPool: false,
      hasWardrobes: false,
      hasFurnished: false,
    };
  }

  // Oficinas: sin habitaciones
  if (propertyType === 'office') {
    return {
      ...features,
      hasBedrooms: false,
      hasBathrooms: true,
      hasBalcony: false,
      hasGarden: false,
      hasPool: false,
      hasWardrobes: false,
    };
  }

  // Locales comerciales: sin habitaciones
  if (propertyType === 'commercial') {
    return {
      ...features,
      hasBedrooms: false,
      hasBathrooms: true,
      hasBalcony: false,
      hasGarden: false,
      hasPool: false,
      hasWardrobes: false,
    };
  }

  // Propiedades residenciales: todas las características
  return features;
}

// Función para obtener una propiedad por ID
export function getPropertyById(id: string): Property | undefined {
  // Primero intentar obtener desde localStorage (propiedades editadas)
  const savedProperties = localStorage.getItem('realmaker_properties');
  if (savedProperties) {
    try {
      const properties = JSON.parse(savedProperties);
      const found = properties.find((prop: Property) => prop.id === id);
      if (found) return found;
    } catch (error) {
      console.error('Error al parsear propiedades guardadas:', error);
    }
  }

  // Si no está en localStorage, devolver la del mock
  return MOCK_PROPERTIES.find((prop) => prop.id === id);
}
