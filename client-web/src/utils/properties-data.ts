  // Metadata
  status: 'available' | 'unavailable' | 'sold' | 'rented' | 'reserved';
  updatedAt: string;
  idealistaUrl?: string;

  // Estadísticas de Idealista (solo si está conectado a Idealista)
  idealistaStats?: {
    views: number; // Visitas
    contacts: number; // Contactos
    favorites: number; // Favoritos
    searchPosition?: number; // Posición en búsqueda (opcional)
  };

  // Marca de agua
  watermarkEnabled?: boolean;
  watermarkPosition?: 'top-left' | 'top-right' | 'bottom-left' | 'bottom-right' | 'center';
  watermarkSize?: 'xs' | 's' | 'm' | 'l' | 'xl';
  watermarkOpacity?: number;
  watermarkRotation?: number;
  watermarkCustomPosition?: { x: number; y: number };
  watermarkWidth?: number;

  // Interesados
  interestedCount?: number;
  interestedLeads?: {
    id: string;
    name: string;
    phone: string;
    email?: string;
    avatarUrl?: string;
    lastContact: string;
    qualification: number;
    source?: 'whatsapp' | 'instagram' | 'messenger' | 'tiktok';
  }[];
